"""Regenerate the Contents section of README.md from the papers' front matter.

Usage:
    python _tools/readme.py            # rewrite README.md in place
    python _tools/readme.py --check    # exit 1 if README.md is out of date

The site builds its home page from `_papers/*.md` front matter; the README is a
static file on GitHub and cannot, so this script writes the same grouping into
it between two marker comments. Run it after adding or revising a paper. The
grouping and the within-track ordering mirror `index.md`: tracks by `label`,
`order` (the write-sequence) within a track. Requires PyYAML.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PAPERS = ROOT / "_papers"
README = ROOT / "README.md"
SITE = "https://idl3o.github.io/derivation-of-value"
BEGIN = "<!-- contents:begin — generated by _tools/readme.py; edit the front matter, not this block -->"
END = "<!-- contents:end -->"
REQUIRED = ("title", "label", "status", "order", "permalink", "blurb")
FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)


@dataclass(frozen=True, slots=True)
class Paper:
    """The front-matter fields the README needs, parsed and checked."""

    title: str
    subtitle: str | None
    label: str
    status: str
    order: int
    permalink: str
    blurb: str
    date: str | None
    hidden: bool
    source: str


def parse(path: Path) -> Paper:
    """Parse one paper's front matter; fail loudly on a missing or mistyped field."""
    text = path.read_text(encoding="utf-8")
    match = FRONT.match(text)
    if not match:
        raise SystemExit(f"{path.name}: no front matter")
    data = yaml.safe_load(match.group(1)) or {}
    missing = [k for k in REQUIRED if k not in data]
    if missing:
        raise SystemExit(f"{path.name}: missing {', '.join(missing)}")
    if not isinstance(data["order"], int):
        raise SystemExit(f"{path.name}: order must be an integer, got {data['order']!r}")
    date = data.get("date")
    return Paper(
        title=str(data["title"]),
        subtitle=str(data["subtitle"]) if data.get("subtitle") else None,
        label=str(data["label"]),
        status=str(data["status"]),
        order=data["order"],
        permalink=str(data["permalink"]),
        blurb=" ".join(str(data["blurb"]).split()),
        date=date.isoformat() if hasattr(date, "isoformat") else (str(date) if date else None),
        hidden=bool(data.get("hidden", False)),
        source=path.name,
    )


def load() -> list[Paper]:
    papers = [parse(p) for p in sorted(PAPERS.glob("*.md"))]
    orders = [p.order for p in papers]
    dupes = sorted({o for o in orders if orders.count(o) > 1})
    if dupes:
        raise SystemExit(f"duplicate order values: {dupes}")
    return sorted(papers, key=lambda p: p.order)


TRACKS = (
    ("Start here", lambda p: p.label == "Companion"),
    ("The anthology", lambda p: "Volume" in p.label),
    ("The framework", lambda p: p.label in ("Framework", "Whitepaper")),
    ("The papers", lambda p: "Paper" in p.label and p.label != "Whitepaper"),
)


def entry(p: Paper) -> str:
    head = f"**[{p.title}]({SITE}{p.permalink})**"
    if p.subtitle:
        head += f" — *{p.subtitle}*"
    meta = " · ".join(x for x in (p.label, p.status, p.date, f"order {p.order}") if x)
    return f"- {head}  \n  {meta}  \n  {p.blurb}"


def render(papers: list[Paper]) -> str:
    shown = [p for p in papers if not p.hidden]
    lines = [BEGIN, "", f"{len(shown)} documents. Grouped by track as on the site; within a track, "
             "in the order they were written (`order`), which is not the order they depend on each other.", ""]
    for name, pick in TRACKS:
        group = [p for p in shown if pick(p)]
        if not group:
            continue
        lines += [f"### {name}", ""] + [entry(p) for p in group] + [""]
    lines.append(END)
    return "\n".join(lines)


def splice(readme: str, block: str) -> str:
    start, stop = readme.find(BEGIN), readme.find(END)
    if start < 0 or stop < 0 or stop < start:
        raise SystemExit("README.md: contents markers not found")
    return readme[:start] + block + readme[stop + len(END):]


def main(argv: list[str]) -> int:
    current = README.read_text(encoding="utf-8")
    updated = splice(current, render(load()))
    if "--check" in argv:
        if updated != current:
            print("README.md is out of date; run python _tools/readme.py", file=sys.stderr)
            return 1
        print("README.md is current")
        return 0
    README.write_text(updated, encoding="utf-8", newline="\n")
    print("README.md regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
